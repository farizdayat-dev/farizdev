document.addEventListener("DOMContentLoaded", function () {

    // Jumlah popup iklan
    const totalPopup = 3;

    // Fungsi menampilkan popup
    function tampilkanPopup(nomor) {

        const popup = document.getElementById(
            "popupIklan" + nomor
        );

        if (popup) {
            popup.style.display = "flex";
        }

    }

    // Fungsi menutup popup
    function tutupPopup(nomor) {

        const popupAktif = document.getElementById(
            "popupIklan" + nomor
        );

        if (!popupAktif) return;

        // Tutup popup saat ini
        popupAktif.style.display = "none";

        // Tampilkan popup berikutnya
        const popupBerikutnya = nomor + 1;

        if (popupBerikutnya <= totalPopup) {

            tampilkanPopup(popupBerikutnya);

        }

    }

    // Pasang event pada seluruh tombol close
    document.querySelectorAll(".popup-close").forEach(function (tombol) {

        tombol.addEventListener("click", function (event) {

            event.preventDefault();
            event.stopPropagation();

            const nomor = Number(
                this.getAttribute("data-close")
            );

            if (nomor >= 1 && nomor <= totalPopup) {
                tutupPopup(nomor);
            }

        });

    });

});
